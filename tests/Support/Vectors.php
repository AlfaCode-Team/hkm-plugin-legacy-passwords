    /**
     * phpass hashes produced by Appwrite's PHPass implementation.
     *
     * The last entry is the first one's hash with its prefix rewritten to
     * `$H$`, which is how phpBB3 writes the identical algorithm — and
     * Appwrite's own verify accepts it, which is what makes it a vector rather
     * than a guess.
     *
     * @return list<array{password: string, hash: string}>
     */
    public static function phpass(): array
    {
        return [
            ['password' => 'secret',
                'hash' => '$P$Be.39vipNM3QIErUZ.CevixuseSbRo0'],
            ['password' => 'correct horse battery staple',
                'hash' => '$P$BUtP.w/r35024g02PAcgc.U8aIwvMN1'],
            // The empty password. A real phpass hash of it, so "empty password"
            // and "empty stored hash" stay distinguishable in the tests.
            ['password' => '',
                'hash' => '$P$B0qp6zm5YzIn5xSqtlOVpe0e2P1Ibi0'],
            // Multi-byte, at a different iteration count ($P$E = 2^16).
            ['password' => 'pässwörd',
                'hash' => '$P$E.WJd0ffShQOUfzGDbRCwQgdyr1UiH/'],
            // $P$J = 2^21 iterations, the heaviest here.
            ['password' => 'a',
                'hash' => '$P$JUBxMY35sx/5B5kAhuN.rfrJnZcY.W0'],
            // phpBB3's prefix, same algorithm, same salt and count.
            ['password' => 'secret',
                'hash' => '$H$Be.39vipNM3QIErUZ.CevixuseSbRo0'],
        ];
    }

    /**
