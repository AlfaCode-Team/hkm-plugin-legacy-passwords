     * own published example. The third is deliberately tiny — a 4-byte signer
     * key and an empty password — because the output length follows the SIGNER
     * KEY rather than any digest size, and nothing else here would catch an
     * implementation that assumed 64 bytes.
     *
     * @return list<array{password: string, salt: string, separator: string, signerKey: string, hash: string}>
     *         salt, separator and signerKey are base64, as an export writes them.
     */
