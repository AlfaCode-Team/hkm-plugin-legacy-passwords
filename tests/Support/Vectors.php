    /**
     * Salted and unsalted digests, generated by Python's hashlib.
     *
     * This is the family Appwrite's importer cannot read at all — its `md5`
     * and `sha` algorithms hash the password and nothing else — so these are
     * the vectors that matter most for a real migration.
     *
     * @return list<array{password: string, salt: string, algorithm: string, placement: string, hex: string}>
     */
    public static function digests(): array
    {
        return [
