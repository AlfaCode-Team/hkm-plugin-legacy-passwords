<?php

declare(strict_types=1);

namespace Tests\Plugins\LegacyPasswords\Support;

/**
 * Known-answer test vectors, and WHERE EACH ONE CAME FROM.
 *
 * ════════════════════════════════════════════════════════════════════════════
 * THE PROVENANCE IS THE POINT OF THIS FILE
 * ════════════════════════════════════════════════════════════════════════════
 *
 * A test vector produced by the code under test proves nothing. It is a test
 * that cannot fail: the implementation agrees with itself, and an
 * implementation that is wrong in the same way twice is exactly as green as
 * one that is right.
 *
 * Every value below was therefore generated by SOMETHING ELSE, on the machine
 * this plugin was written on, and the tool is named against each group so a
 * future reader can regenerate it rather than trust it:
 *
 *   scrypt            Python's `hashlib.scrypt` (OpenSSL) AND Node's
 *                     `crypto.scryptSync` — two implementations, which agree
 *                     with each other and with RFC 7914 §11's published
 *                     vectors. The RFC values were CONFIRMED by those two
 *                     rather than recalled.
 *   Firebase          Node end to end: `crypto.scryptSync` for the derivation,
 *                     `crypto.createCipheriv('aes-256-ctr', …)` for the
 *                     encryption. Neither half checked against itself.
 *   phpass            Appwrite's `Utopia\Auth\Hashes\PHPass`, a completely
 *                     separate PHP implementation, run locally. Includes a
 *                     `$H$`-prefixed (phpBB3) hash.
 *   PBKDF2            Python's `hashlib.pbkdf2_hmac`, assembled into Django's
 *                     string format.
 *   digests           Python's `hashlib`.
 *   crypt(3)          `openssl passwd -1/-5/-6`, which agrees with PHP's own
 *                     `crypt()` — two independent implementations again.
 *   bcrypt / Argon2   PHP's own `password_hash`, which is the only correct
 *                     oracle: `password_verify` is what will check them in
 *                     production, so a vector from anywhere else would be
 *                     testing a different thing.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * THE PASSWORDS ARE DELIBERATELY AWKWARD
 * ────────────────────────────────────────────────────────────────────────────
 *
 * An empty string, a multi-byte one, and one with a space. The empty password
 * matters most: several of these schemes will happily verify SOMETHING against
 * an empty stored hash, and `hash_equals('', '')` is true — so the empty cases
 * are what prove the guards rather than decorating the table.
 */
final class Vectors
{
    /**
     * RFC 7914 §11, confirmed by Python and Node.
     *
     * Vector 4 (N=2^20) is omitted: it needs a gigabyte and, at this
     * implementation's measured rate, several minutes. It tests nothing the
     * other three do not — the parameters are the same shape, only larger.
     *
     * @return list<array{0: string, 1: string, 2: int, 3: int, 4: int, 5: int, 6: string}>
     *         password, salt, N, r, p, dkLen, expected hex
     */
    public static function scrypt(): array
    {
        return [
            // The degenerate case. r=1 is the one where BlockMix's even/odd
            // reordering is the identity, so a broken implementation of that
            // step PASSES this vector — which is precisely why the other two
            // are not optional.
            ['', '', 16, 1, 1, 64,
                '77d6576238657b203b19ca42c18a0497f16b4844e3074ae8dfdffa3fede21442'
                . 'fcd0069ded0948f8326a753a0fc81f17e8d3e0fb2e0d3628cf35e20c38d18906'],

            // p=16, which is the only vector that exercises the loop over p at
            // all. With p=1 an implementation that ignored p entirely would
            // still pass everything else here.
            ['password', 'NaCl', 1024, 8, 16, 64,
                'fdbabe1c9d3472007856e7190d01e9fe7c6ad7cbc8237830e77376634b373162'
                . '2eaf30d92e22a3886ff109279d9830dac727afb94a83ee6d8360cbdfa2cc0640'],

            // N=16384, r=8, p=1 — exactly Firebase's default configuration,
            // and the one whose cost was measured at 1.58 s.
            ['pleaseletmein', 'SodiumChloride', 16384, 8, 1, 64,
                '7023bdcb3afd7348461c06cd81fd38ebfda8fbba904f8e3ea9b543f6545da1f2'
                . 'd5432955613f0fcf62d49705242a9af9e61e85dc0d651e40dfcf017b45575887'],
        ];
    }

